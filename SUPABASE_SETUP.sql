-- Run this once in Supabase Dashboard > SQL Editor > New query.
create table if not exists public.testimonials (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  rating smallint not null check (rating between 1 and 5),
  review text not null check (char_length(review) between 1 and 1200),
  image_url text,
  created_at timestamptz not null default now()
);

alter table public.testimonials enable row level security;
grant select, insert on public.testimonials to anon;

drop policy if exists "Anyone can read testimonials" on public.testimonials;
create policy "Anyone can read testimonials"
  on public.testimonials for select to anon using (true);

drop policy if exists "Anyone can submit testimonials" on public.testimonials;
create policy "Anyone can submit testimonials"
  on public.testimonials for insert to anon
  with check (
    char_length(name) between 1 and 80
    and rating between 1 and 5
    and char_length(review) between 1 and 1200
  );

-- Public image bucket, limited to image files up to 3 MB each.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('testimonials', 'testimonials', true, 3145728,
        array['image/jpeg', 'image/png', 'image/webp', 'image/gif'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Anyone can upload testimonial photos" on storage.objects;
create policy "Anyone can upload testimonial photos"
  on storage.objects for insert to anon
  with check (bucket_id = 'testimonials');

drop policy if exists "Anyone can read testimonial photos" on storage.objects;
create policy "Anyone can read testimonial photos"
  on storage.objects for select to anon
  using (bucket_id = 'testimonials');
